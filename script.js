const frenchTextNodes = new WeakMap();

function translatePortfolio(language) {
    const isEnglish = language === "en";
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);

    while (walker.nextNode()) {
        const node = walker.currentNode;
        if (node.parentElement && node.parentElement.closest("#language-toggle")) continue;

        const originalText = node.textContent;
        const content = originalText.trim().replace(/\s+/g, " ");
        const translation = englishTranslations[content];
        if (isEnglish && translation) {
            const leadingWhitespace = originalText.match(/^\s*/)[0];
            const trailingWhitespace = originalText.match(/\s*$/)[0];
            frenchTextNodes.set(node, originalText);
            node.textContent = `${leadingWhitespace}${translation}${trailingWhitespace}`;
        } else if (!isEnglish && frenchTextNodes.has(node)) {
            node.textContent = frenchTextNodes.get(node);
            frenchTextNodes.delete(node);
        }
    }

    document.querySelectorAll("[alt], [aria-label]").forEach(element => {
        ["alt", "aria-label"].forEach(attribute => {
            const originalValue = element.getAttribute(attribute);
            const translation = originalValue && englishAttributes[originalValue];
            const dataAttribute = `french${attribute === "aria-label" ? "AriaLabel" : "Alt"}`;

            if (isEnglish && translation) {
                element.dataset[dataAttribute] = originalValue;
                element.setAttribute(attribute, translation);
            } else if (!isEnglish && element.dataset[dataAttribute]) {
                element.setAttribute(attribute, element.dataset[dataAttribute]);
                delete element.dataset[dataAttribute];
            }
        });
    });

    document.documentElement.lang = language;
    document.title = isEnglish ? "Mathis Besnier's Portfolio" : "Portfolio Mathis Besnier";
    const languageButton = document.getElementById("language-toggle");
    languageButton.lang = isEnglish ? "fr" : "en";
    languageButton.setAttribute("aria-pressed", String(isEnglish));
    languageButton.setAttribute("aria-label", isEnglish ? "Switch to French" : "Passer en anglais");
}

